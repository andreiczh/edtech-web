/**
 * Человеческое объяснение сетевого сбоя при запросе к бэкенду.
 *
 * Старый текст был один на все случаи: «Не достучались до бэкенда. Он запущен
 * на :8000?». Когда страницу отдал туннель, он врал дважды: бэкенд там на том же
 * origin, никакого :8000 у браузера нет, а реальная причина — оборвавшийся
 * туннель, а не незапущенный сервер. Человек шёл проверять не то.
 *
 * Отличать случаи можно по тому, откуда пришла сама страница.
 */
/**
 * Объяснение НЕуспешного HTTP-ответа.
 *
 * Раньше на экран уходило голое «HTTP 502», и это худший вид ошибки: код есть,
 * смысла нет. В `docs/DECISIONS.md` §5 записано, что именно непрозрачная ошибка
 * однажды стоила проекту нескольких дней.
 *
 * Важно различать, ЧЕЙ это 502. Наш бэкенд тоже отвечает 502 (например, когда
 * упал STT или LLM), но всегда с полем `detail` — тогда показываем его. А голый
 * 502/503/504 без тела приходит от того, кто стоит МЕЖДУ браузером и сервером,
 * то есть от туннеля: сам сервер при этом жив и по localhost работает.
 */
export function httpErrorMessage(status: number, detail?: string | null): string {
  if (detail) return detail
  if (status === 502 || status === 503 || status === 504) {
    const host = window.location.hostname
    return (
      `Туннель не смог достучаться до сервера (HTTP ${status}). Сам сервер, скорее всего, ` +
      `жив — оборвался туннель ${host}, они живут по 20–30 минут. ` +
      'Если ты за тем же компьютером, где запущен сервер, открой http://localhost:8000/ — ' +
      'там туннеля нет и рваться нечему.'
    )
  }
  return `Сервер ответил HTTP ${status} без объяснения.`
}

export function backendUnreachableMessage(): string {
  const host = window.location.hostname
  const isLocal = host === 'localhost' || host === '127.0.0.1' || host === '[::1]'

  if (isLocal) {
    return 'Сервер не отвечает. Проверь окно, где он запущен — оно закрыто или там ошибка?'
  }

  return (
    `Связь оборвалась по дороге (${host}). Страница открыта не с этого компьютера напрямую, ` +
    'а через туннель — он и рвётся. Если ты за тем же компьютером, где запущен сервер, ' +
    'открой http://localhost:8000/ — там ничего рваться не может.'
  )
}
