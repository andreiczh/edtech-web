/**
 * Человеческое объяснение сетевого сбоя при запросе к бэкенду.
 *
 * Старый текст был один на все случаи: «Не достучались до бэкенда. Он запущен
 * на :8000?». Когда страницу отдал туннель, он врал дважды: бэкенд там на том же
 * origin, никакого :8000 у браузера нет, а реальная причина — оборвавшийся
 * туннель, а не незапущенный сервер. Человек шёл проверять не то.
 *
 * Отличать случаи можно по тому, откуда пришла сама страница.
 */
export function backendUnreachableMessage(): string {
  const host = window.location.hostname
  const isLocal = host === 'localhost' || host === '127.0.0.1' || host === '[::1]'

  if (isLocal) {
    return 'Сервер не отвечает. Проверь окно, где он запущен — оно закрыто или там ошибка?'
  }

  return (
    `Связь оборвалась по дороге (${host}). Страница открыта не с этого компьютера напрямую, ` +
    'а через туннель — он и рвётся. Если ты за тем же компьютером, где запущен сервер, ' +
    'открой http://localhost:8000/ — там ничего рваться не может.'
  )
}
