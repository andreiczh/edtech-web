"""Что разрешено озвучивать через /speak — и насколько крепко это проверено.

Зачем появилось (21.08.2026). В задании 39 ученику показывают слово, которое
он прочитал не так. Услышать это слово — ровно то, чего разбору не хватало:
текст на экране не отвечает на вопрос «а как надо?». Кнопку добавляем, но
озвучка стоит квоты Mistral, а `/speak` до сих пор принимал ЛЮБОЙ текст до
400 знаков — докстринг обещал «только вопросы из банка», проверки в коде не
было вовсе. Раз трогаем ручку, дырку закрываем заодно.

Защита двуслойная, и слои РАЗНОЙ силы. Это надо понимать, а не прятать:

1. **ФОРМА — работает всегда.** В режиме слова принимается не больше трёх
   токенов из английских букв, апострофа и дефиса, всего до 48 знаков.
   Свободного синтезатора речи из такого не сделать при лимите 40 запросов
   в минуту на аккаунт.

2. **ЭТАЛОН — работает, когда вариант ЕСТЬ В БАЗЕ.** Задание из банка сервер
   находит по id и требует, чтобы каждое слово нашлось в его тексте. У
   ВСТРОЕННЫХ вариантов (`39-1` и соседи живут только в коде фронта) текста
   на сервере нет, и сверять не с чем — там держит одна форма. Второй раз
   писать в докстринге неправду об этом не будем.

Модуль чистый: ни сети, ни базы. Тест — `test_speak_check.py`.
"""

from __future__ import annotations

import re

# Потолки режима слова. 48 знаков — это «medium-sized» с запасом; три токена
# нужны потому, что ошибка чтения бывает не в одном слове («can not» вместо
# «can't»), а связка из двух-трёх слов ещё остаётся ОБРАЗЦОМ ПРОИЗНОШЕНИЯ,
# а не фразой, которую хочется синтезировать бесплатно.
WORD_MAX_CHARS = 48
WORD_MAX_TOKENS = 3

# Типографские апострофы: у ФИПИ в текстах «can’t», а модель и клавиатура дают
# «can't». Для сверки это одно и то же слово, и разойтись они не должны.
_APOSTROPHES = "’‘ʼ´`"
# Дефис (в том числе длинные тире) РАЗДЕЛЯЕТ слова: «medium-sized» в эталоне и
# «medium sized» в цитате обязаны сойтись.
_HYPHENS = "‐‑‒–—―"

_WORD_RE = re.compile(r"[a-z][a-z']*")
# Что вообще позволено видеть в запросе на слово: буквы, пробелы, апостроф,
# дефис. Цифры, точки и запятые означают, что просят не слово, а текст.
_ALLOWED_RE = re.compile(r"^[A-Za-z\s'\-]+$")


def normalize(text: str) -> str:
    """Привести к виду, в котором слова сравнимы: строчные, один апостроф,
    дефис — как пробел."""
    s = str(text or "")
    for ch in _APOSTROPHES:
        s = s.replace(ch, "'")
    for ch in _HYPHENS:
        s = s.replace(ch, "-")
    return s.lower()


def words(text: str) -> list[str]:
    """Слова текста в сравнимом виде. Апострофы по краям срезаются: в эталоне
    слово может стоять в кавычках-апострофах, и «'parrot'» — это parrot."""
    flat = normalize(text).replace("-", " ")
    return [w.strip("'") for w in _WORD_RE.findall(flat) if w.strip("'")]


def word_problem(text: str) -> str:
    """Почему это НЕ образец произношения — или пустая строка.

    Причина возвращается по-русски: она доедет до ученика, а не только в лог.
    """
    raw = str(text or "").strip()
    if not raw:
        return "Нечего озвучивать."
    if len(raw) > WORD_MAX_CHARS:
        return "Слишком длинный кусок — озвучиваю отдельное слово, не текст."
    # normalize уже свёл типографские апострофы и тире к обычным, поэтому
    # набор разрешённых знаков проверяется по нормализованному тексту.
    if not _ALLOWED_RE.match(normalize(raw)):
        return "Озвучиваю только английские слова."
    got = words(raw)
    if not got:
        return "Озвучиваю только английские слова."
    if len(got) > WORD_MAX_TOKENS:
        return (f"Слишком много слов: {len(got)}, а озвучиваю не больше "
                f"{WORD_MAX_TOKENS}.")
    return ""


def missing_from(text: str, reference: str) -> list[str]:
    """Слова, которых в эталоне НЕТ. Пустой список — всё нашлось.

    Сверка пословная, а не по вхождению подстроки, и это не придирка:
    подстрокой «par» находится внутри «parrot», и проверка пропускала бы
    любой обрывок. Порядок слов не требуется — цитата из разбора может
    склеивать соседние куски.
    """
    pool = set(words(reference))
    if not pool:
        return []
    return [w for w in words(text) if w not in pool]
