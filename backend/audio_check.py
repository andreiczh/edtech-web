"""Осмотр записи ДО распознавания: есть ли там вообще речь.

Зачем это появилось (05.08.2026, по разбору жалоб тестировщика). Ученик ничего
не сказал — и получил разбор чужого текста. Воспроизведено на этой машине:
шесть секунд тишины с шумом микрофонного пола Voxtral превратил в
**960 слов** сочинённого монолога («Hello, my name is Sasha. I'm 15 years
old...»). У тестировщика та же поломка вылезла кусками «Мастера и Маргариты».

Это свойство распознавания, а не наша ошибка в коде: модель обязана что-то
вернуть и на пустом входе выдаёт самое вероятное. Но последствие наше — ученику
приписывается несказанное, и он теряет доверие ко всему разбору сразу.

Единственная надёжная защита — не спрашивать. Тишину видно из САМОГО ЗВУКА,
арифметикой, до всякой модели: у неё нет громких кадров. Заодно экономится
вызов распознавания и вызов LLM.

Второй случай, который ловится здесь же: распознавание вернуло горстку слов на
длинной записи. Ученик говорил сорок секунд, а в транскрипте два слова — это
провал распознавания, а НЕ провал ученика, и обвинять его нельзя. Тестировщик
поймал ровно это: «пишет, я прочитал только 2 слова, хотя фактически прочитал
предложение».

Все пороги — с большим запасом в пользу ученика: сомнительное считается речью.
"""

from __future__ import annotations

import io

import av
import numpy as np

# Кадр считаем «громким», если его среднеквадратичная амплитуда выше этого.
# 0.01 от полной шкалы — это примерно −40 дБFS: тише говорит только тот, кто
# не говорит. Шум микрофонного пола на порядок ниже.
_LOUD_RMS = 0.01
_FRAME_MS = 30

# Доля громких кадров, ниже которой запись считается пустой. Два процента от
# сорока секунд — меньше секунды звука: даже одно слово даёт больше.
_MIN_SPEECH_RATIO = 0.02

# Совсем короткая запись — не ответ. Полторы секунды не хватает даже на
# «I don't know».
_MIN_SECONDS = 1.5

# Ниже стольких слов в минуту распознавание считается провалившимся, а не
# ученик — молчавшим. Медленное чтение вслух — 90 слов/мин, очень медленная
# спонтанная речь — 60. Порог 25 не задевает никого, кто действительно говорил.
_MIN_WPM = 25
# Столько РЕЧИ нужно, чтобы судить о темпе. На коротком куске одно слово —
# нормальный ответ на «yes or no».
_WPM_MIN_SPEECH_SECONDS = 8.0

# Для темпа порог громкости ПОДНИМАЕТСЯ вместе с шумом комнаты: во столько раз
# кадр должен быть громче медианного, чтобы считаться речью. У записи с шумным
# микрофоном (архив ФИПИ, работа 4596: пол 0.034 при пороге 0.01) весь файл
# считался речью, 29 слов на 79 «секунд речи» давали 22 сл/мин — и здоровый
# ответ отвергался как провал распознавания. Медиана кадров в записях с паузами
# (40/41 — ученик большую часть времени думает) — это и есть шум пола; на
# сплошной речи медиана оказывается ВНУТРИ речи, секунды речи занижаются, темп
# завышается — то есть ложных отказов множитель не добавляет ни там, ни там.
_NOISE_MULT = 2.0


def sniff(data: bytes) -> str:
    """Контейнер записи по первым байтам, а не по имени файла.

    Имя и тип файла назначает браузер, и они врут: iPhone пишет mp4, а фронт
    до 15.09.2026 подписывал любую запись как webm. Байты не врут.
    """
    h = data[:12]
    if len(h) >= 8 and h[4:8] == b"ftyp":
        return "mp4"
    if h[:4] == b"\x1a\x45\xdf\xa3":
        return "webm"
    if h[:4] == b"OggS":
        return "ogg"
    if h[:4] == b"RIFF" and h[8:12] == b"WAVE":
        return "wav"
    if h[:4] == b"fLaC":
        return "flac"
    if len(h) >= 2 and h[0] == 0xFF and (h[1] & 0xF6) == 0xF0:
        return "aac"  # ADTS: синхрослово как у mp3, но биты слоя — 00
    if h[:3] == b"ID3" or (len(h) >= 2 and h[0] == 0xFF and (h[1] & 0xE0) == 0xE0):
        return "mp3"
    return "unknown"


def to_pcm(data: bytes, ext: str = ".webm") -> np.ndarray | None:
    """Байты записи -> моно float32 16 кГц. None, если декодировать не вышло.

    Вынесено отдельно, потому что тот же звук нужен не только осмотру: по нему
    же считается произношение (gop.py). Декодируем тем же PyAV, что уже стоит
    ради перекодирования в wav, — новой зависимости не появляется.
    """
    def decode(fmt: str | None) -> list[np.ndarray]:
        with av.open(io.BytesIO(data), format=fmt) as c:
            rs = av.audio.resampler.AudioResampler(format="s16", layout="mono",
                                                   rate=16000)
            got: list[np.ndarray] = []
            for frame in c.decode(audio=0):
                for f in rs.resample(frame):
                    got.append(f.to_ndarray().reshape(-1))
            return got

    try:
        chunks = decode(ext.lstrip(".") or None)
    except Exception:
        try:  # формат не угадали — пусть PyAV определит сам
            chunks = decode(None)
        except Exception:
            return None
    if not chunks:
        return np.zeros(0, dtype=np.float32)
    return np.concatenate(chunks).astype(np.float32) / 32768.0


def inspect(data: bytes, ext: str = ".webm") -> dict:
    """Длительность и доля кадров с речью. Ошибка разбора — не приговор:
    возвращаем ok=False, и все проверки ниже пропускают запись дальше.
    """
    pcm = to_pcm(data, ext)
    if pcm is None:
        return {"ok": False}
    if len(pcm) == 0:
        return {"ok": True, "seconds": 0.0, "speech_ratio": 0.0}

    sr = 16000
    step = int(sr * _FRAME_MS / 1000)
    if step <= 0 or len(pcm) < step:
        return {"ok": True, "seconds": len(pcm) / sr, "speech_ratio": 0.0}

    frames = pcm[: len(pcm) // step * step].reshape(-1, step)
    rms = np.sqrt((frames ** 2).mean(axis=1))
    # Два счёта речи с разными порогами — потому что у проверок разные цены
    # ошибки. Абсолютный порог (для silence_reason) от шума только РАСТЁТ, то
    # есть ошибается в сторону «речь есть» — в пользу ученика. Адаптивный (для
    # recognition_failed) вычитает шум комнаты, иначе на шумном микрофоне
    # паузы считаются речью и здоровый ответ объявляется сбоем распознавания.
    loud_thr = max(_LOUD_RMS, _NOISE_MULT * float(np.median(rms)))
    return {
        "ok": True,
        "seconds": round(len(pcm) / sr, 2),
        "speech_ratio": round(float((rms > _LOUD_RMS).mean()), 4),
        "speech_ratio_robust": round(float((rms > loud_thr).mean()), 4),
    }


def silence_reason(info: dict) -> str | None:
    """Почему эту запись нельзя разбирать. None — можно."""
    if not info.get("ok"):
        return None  # не смогли посмотреть — не мешаем
    seconds = float(info.get("seconds") or 0.0)
    # Текст уже с заглавной: str.capitalize() на стороне вызова опускал бы
    # регистр во всём остальном предложении («…тишина. проверь, что микрофон»).
    if seconds < _MIN_SECONDS:
        return ("Запись почти пустая — она длится меньше двух секунд. "
                "Проверь микрофон и попробуй ещё раз.")
    if float(info.get("speech_ratio") or 0.0) < _MIN_SPEECH_RATIO:
        return ("В записи нет речи — только тишина. Проверь, что микрофон "
                "включён и разрешён в браузере, и попробуй ещё раз.")
    return None


def speech_seconds(info: dict) -> float:
    """Сколько в записи РЕЧИ, а не тишины и не шума комнаты.

    Берётся адаптивная доля (порог поднят над шумом пола); у записей, снятых
    до появления этого поля, — обычная.
    """
    ratio = info.get("speech_ratio_robust")
    if ratio is None:
        ratio = info.get("speech_ratio") or 0.0
    return float(info.get("seconds") or 0.0) * float(ratio)


def recognition_failed(info: dict, transcript: str) -> bool:
    """Похоже ли, что распознавание не справилось, хотя человек говорил.

    Признак: РЕЧИ много, а слов почти нет. Виноват не ученик, и обвинять его
    нулём за «слишком короткий ответ» нечестно — честнее сказать, что не
    расслышали, и дать переписать.

    Темп считается от секунд РЕЧИ, а не от длины файла, и это не уточнение, а
    исправление настоящей поломки (05.08.2026). В заданиях 40 и 41 паузы
    заложены в само задание: ученику дают 20 секунд на вопрос и 40 на ответ, и
    почти всё это время он молчит — думает. Запись выходит длинной, слов в ней
    мало, и проверка от полной длины отвергала КАЖДУЮ такую работу:

        №40, четыре коротких вопроса: 20 слов на 80 с записи =  15 сл/мин -> отказ
        №41, короткие ответы:         15 слов на 200 с       =   4 сл/мин -> отказ

    А от реальной речи те же работы дают 214 и 75 слов/мин — то есть с
    распознаванием всё в порядке. При этом настоящий сбой ловится по-прежнему:
    «говорил 40 секунд (24 с речи), распознали 2 слова» = 5 сл/мин.

    Тестировщик видел это как «не удалось разобрать» и бесполезную кнопку
    «Повторить разбор»: повтор слал ту же запись и получал тот же приговор.
    """
    if not info.get("ok"):
        return False
    if float(info.get("speech_ratio") or 0.0) < _MIN_SPEECH_RATIO:
        return False  # тишину ловит silence_reason, это другой случай
    speech = speech_seconds(info)
    if speech < _WPM_MIN_SPEECH_SECONDS:
        return False
    words = len(transcript.split())
    return (words * 60.0 / speech) < _MIN_WPM
