"""Разбор разговора: что было хорошо, что чинить, что сказать в следующий раз.

Зачем (04.08.2026). В разговорном режиме ошибки ученика раньше ИСПАРЯЛИСЬ:
собеседник поправлял максимум одну штуку за реплику и ехал дальше, а в конце
не оставалось ничего. Человек говорил двадцать минут и уходил без единого
вывода — отсюда жалоба «не разбирает ошибки или делает это мимоходом».

Устройство простое и намеренно дешёвое:
  * ОДИН вызов LLM на всю сессию, по явному нажатию «Завершить и разобрать».
    Не на каждую реплику и не автоматически при уходе с экрана — иначе разбор
    жёг бы бюджет молча и за спиной у ученика.
  * Вход — та же клиентская история, что уже ездит с каждой репликой. Никакого
    нового хранилища и никаких транскриптов на сервере.
  * Выход — JSON фиксированной формы, который фронт рисует карточкой.

Главное правило промпта — ЗАПРЕТ ВЫДУМЫВАТЬ. Цитата обязана быть скопирована
из реплики ученика дословно; сервер это проверяет сам (`_verify`) и молча
выбрасывает всё, чего в тексте не было. Разбор, который приписывает ученику
несказанное, хуже отсутствия разбора: ему перестают верить целиком.
"""

from __future__ import annotations

import re

# Сколько обменов нужно, чтобы разбор имел смысл. По трём фразам сказать нечего,
# а вызов LLM стоит столько же, сколько по двадцати.
MIN_EXCHANGES = 3

# Потолки на то, что показываем. Экран не должен превращаться в простыню:
# пять ошибок человек ещё исправит, пятнадцать — просто закроет.
MAX_MISTAKES = 5
MAX_GOOD = 3
MAX_PHRASES = 4

SCHEMA_HINT = """{
  "summary": "<2-3 предложения по-русски: о чём говорили и как ученик справился>",
  "mistakes": [
    {"quote": "<точные слова ученика, скопированные из его реплики>",
     "correction": "<как надо сказать по-английски>",
     "why": "<по-русски, до 12 слов: какое правило нарушено>"}
  ],
  "good": ["<точная английская фраза ученика, которая вышла удачно>"],
  "phrases": [
    {"en": "<полезная фраза по теме, которой ученик НЕ пользовался>",
     "ru": "<перевод>"}
  ]
}"""


def build_prompt(tone: str) -> str:
    """Системный промпт разбора. Тон — от персоны, правила — общие для всех.

    Названия темы здесь НЕТ намеренно, хотя тема у беседы есть. Проверено
    04.08.2026: когда тема ехала в промпт, модель верила ЕЙ, а не расшифровке.
    Ученик начал с темы «Что изменить в школе», разговорился про кино — и разбор
    бодро сообщил, что «ученик обсуждал, как можно изменить школу», и предложил
    четыре фразы про школьные столовые. Уход от темы разрешён самим промптом
    разговора («иди за учеником»), поэтому единственный источник правды для
    разбора — расшифровка.
    """
    return (
        "Ты преподаватель английского. Ниже — расшифровка разговорной практики с "
        "русскоязычным учеником (уровень A2-B1), который готовится к устной части "
        "ЕГЭ. Строки STUDENT — это АВТОМАТИЧЕСКОЕ распознавание его речи, строки "
        "PARTNER — реплики собеседника, они даны только как контекст.\n"
        "Суди ТОЛЬКО по этой расшифровке: о чём говорили, видно из неё и больше "
        "ниоткуда.\n"
        "\nВерни ТОЛЬКО JSON такой формы:\n"
        f"{SCHEMA_HINT}\n"
        "\nПРАВИЛА, которые важнее стиля:\n"
        f"1. mistakes — не больше {MAX_MISTAKES} штук, самые значимые: сначала то, "
        "что ломает смысл, затем грамматика, которую снимают на экзамене, затем "
        "выбор слова.\n"
        "2. ЗАПРЕЩЕНО выдумывать ошибку, которой нет в тексте. Поле quote должно "
        "быть скопировано из строки STUDENT ДОСЛОВНО, слово в слово. Ошибок "
        "меньше — верни меньше. Ошибок нет — верни пустой список.\n"
        "3. Если предложение грамматически ВЕРНО — не трогай его. Переписывать "
        "правильное ради красоты запрещено: это не ошибка, а твой вкус.\n"
        "4. correction обязан сохранять СМЫСЛ сказанного. «my mother asked me to "
        "help» нельзя чинить в «my mother makes me help» — это другое "
        "утверждение, а не исправление.\n"
        "5. ЗАПРЕЩЕНО судить о произношении, акценте и интонации: ты читаешь "
        "расшифровку, звука ты не слышал.\n"
        "6. Мусор распознавания (одиночные рваные слова, случайные заглавные) — "
        "НЕ ошибка ученика, пропускай его молча.\n"
        f"7. good — от 0 до {MAX_GOOD} фраз, которые ученик действительно сказал и "
        "сказал верно, и которые не тривиальны («yes», «I like it» не годятся). "
        "Копируй дословно.\n"
        f"8. phrases — {MAX_PHRASES} оборота уровня A2-B1 ПО ТОМУ, О ЧЁМ РЕАЛЬНО "
        "ШЛА РЕЧЬ в расшифровке, которыми ученик не воспользовался, но которые "
        "пригодились бы ему в этом самом разговоре.\n"
        "9. Русский текст — простой и на «ты». Никакого markdown, никаких "
        "звёздочек и списков внутри строк.\n"
        f"\nТОН РАЗБОРА: {tone}"
    )


def transcript_of(history: list[dict]) -> str:
    """История в вид, который читает модель. Роли подписаны явно: без подписи
    модель начинала чинить реплики собеседника, а не ученика."""
    lines = []
    for m in history:
        who = "STUDENT" if m.get("role") == "user" else "PARTNER"
        text = str(m.get("content") or "").strip()
        if text:
            lines.append(f"{who}: {text}")
    return "\n".join(lines)


def student_text(history: list[dict]) -> str:
    """Всё, что сказал ученик, одной строкой — по ней проверяются цитаты."""
    return " ".join(
        str(m.get("content") or "") for m in history if m.get("role") == "user"
    )


def _norm(s: str) -> str:
    """Для сверки цитаты: регистр и пунктуация не считаются. Распознавание
    расставляет запятые как хочет, и придираться к ним значило бы выбрасывать
    верные находки. Пробелы схлопываются: «cinema, with» и «cinema with» —
    одна и та же фраза, а не разные (на этом сверка один раз уже споткнулась).
    Края добиты пробелами, чтобы «go» не считалось найденным внутри «goes»."""
    return " " + re.sub(r"[^a-z0-9]+", " ", s.lower()).strip() + " "


def _clean(s: object, limit: int) -> str:
    return re.sub(r"\s+", " ", str(s or "")).strip()[:limit]


def verify(raw: object, history: list[dict]) -> dict:
    """Ответ модели → то, что можно показать ученику.

    Здесь же единственная настоящая защита от выдумок: цитата, которой нет в
    речи ученика, выбрасывается. Модель может ошибиться в разборе — это
    поправимо; приписать ученику несказанное — нет.
    """
    data = raw if isinstance(raw, dict) else {}
    said = _norm(student_text(history))

    mistakes = []
    for m in (data.get("mistakes") or [])[: MAX_MISTAKES * 2]:
        if not isinstance(m, dict):
            continue
        quote = _clean(m.get("quote"), 200)
        correction = _clean(m.get("correction"), 200)
        if not quote or not correction:
            continue
        if _norm(quote) not in said:  # не говорил такого — не показываем
            continue
        mistakes.append({
            "quote": quote,
            "correction": correction,
            "why": _clean(m.get("why"), 160),
        })
        if len(mistakes) >= MAX_MISTAKES:
            break

    good = []
    for g in (data.get("good") or [])[: MAX_GOOD * 2]:
        text = _clean(g, 200)
        if text and _norm(text) in said:
            good.append(text)
        if len(good) >= MAX_GOOD:
            break

    phrases = []
    for p in (data.get("phrases") or [])[: MAX_PHRASES * 2]:
        if not isinstance(p, dict):
            continue
        en = _clean(p.get("en"), 120)
        if not en:
            continue
        phrases.append({"en": en, "ru": _clean(p.get("ru"), 120)})
        if len(phrases) >= MAX_PHRASES:
            break

    turns = sum(1 for m in history if m.get("role") == "user")
    words = len([w for w in student_text(history).split() if w])
    return {
        "summary": _clean(data.get("summary"), 600),
        "mistakes": mistakes,
        "good": good,
        "phrases": phrases,
        # Счётчики считает СЕРВЕР, а не модель: числа модель путает, а здесь
        # они точны по построению и не стоят ни одного лишнего токена.
        "stats": {"turns": turns, "words": words},
    }
